import type { DesignTokens } from './messaging';
import { quoteFamily } from './extract';

// Pure exporters: DesignTokens in, string out. Unit-tested in exporters.test.ts.

type Pair = [string, string];

/** Base variable names (no sigil) shared by the CSS and SCSS exporters. */
function baseGroups(t: DesignTokens): { title: string; pairs: Pair[] }[] {
  return [
    { title: 'Colors', pairs: t.colors.map((c, i): Pair => [`color-${i + 1}`, c]) },
    { title: 'Color roles', pairs: Object.entries(t.roles).map(([k, v]): Pair => [`color-${k}`, v]) },
    {
      title: 'Font families',
      pairs: t.fontFamilies.map((f, i): Pair => [`font-${i + 1}`, `${quoteFamily(f)}, sans-serif`]),
    },
    { title: 'Font sizes', pairs: t.fontSizes.map((s, i): Pair => [`text-${i + 1}`, s]) },
    { title: 'Font weights', pairs: t.fontWeights.map((w, i): Pair => [`weight-${i + 1}`, String(w)]) },
    { title: 'Line heights', pairs: t.lineHeights.map((l, i): Pair => [`leading-${i + 1}`, l]) },
    { title: 'Spacing', pairs: t.spacing.map((s, i): Pair => [`space-${i + 1}`, s]) },
    { title: 'Radii', pairs: t.radii.map((r, i): Pair => [`radius-${i + 1}`, r]) },
    { title: 'Shadows', pairs: t.shadows.map((s, i): Pair => [`shadow-${i + 1}`, s]) },
    { title: 'Gradients', pairs: t.gradients.map((g, i): Pair => [`gradient-${i + 1}`, g]) },
    { title: 'Breakpoints', pairs: t.breakpoints.map((b, i): Pair => [`bp-${i + 1}`, b]) },
  ].filter((g) => g.pairs.length > 0);
}

export function exportCss(t: DesignTokens): string {
  const out = [':root {'];
  for (const g of baseGroups(t)) {
    out.push(`  /* ${g.title} */`);
    for (const [k, v] of g.pairs) out.push(`  --${k}: ${v};`);
  }
  out.push('}');
  return out.join('\n') + '\n';
}

export function exportScss(t: DesignTokens): string {
  const out: string[] = [];
  for (const g of baseGroups(t)) {
    out.push(`// ${g.title}`);
    for (const [k, v] of g.pairs) out.push(`$${k}: ${v};`);
    out.push('');
  }
  return out.join('\n');
}

export function exportTailwind(t: DesignTokens): string {
  const out = ['@import "tailwindcss";', '', '@theme {'];
  const sec = (title: string, pairs: Pair[]) => {
    if (pairs.length === 0) return;
    out.push(`  /* ${title} */`);
    for (const [k, v] of pairs) out.push(`  --${k}: ${v};`);
  };
  sec('Colors', t.colors.map((c, i): Pair => [`color-${i + 1}`, c]));
  sec('Color roles', Object.entries(t.roles).map(([k, v]): Pair => [`color-${k}`, v]));
  sec('Fonts', t.fontFamilies.map((f, i): Pair => [i === 0 ? 'font-sans' : `font-${i + 1}`, `${quoteFamily(f)}, sans-serif`]));
  sec('Text sizes', t.fontSizes.map((s, i): Pair => [`text-${i + 1}`, s]));
  sec('Spacing', t.spacing.map((s, i): Pair => [`spacing-${i + 1}`, s]));
  sec('Radius', t.radii.map((r, i): Pair => [`radius-${i + 1}`, r]));
  sec('Shadow', t.shadows.map((s, i): Pair => [`shadow-${i + 1}`, s]));
  out.push('}');
  return out.join('\n') + '\n';
}

export function exportJson(t: DesignTokens): string {
  const idx = <T>(arr: T[], make: (v: T) => unknown): Record<string, unknown> => {
    const o: Record<string, unknown> = {};
    arr.forEach((v, i) => {
      o[String(i + 1)] = make(v);
    });
    return o;
  };
  const color: Record<string, unknown> = idx(t.colors, (c) => ({ $value: c, $type: 'color' }));
  for (const [k, v] of Object.entries(t.roles)) color[k] = { $value: v, $type: 'color' };

  const doc = {
    $description: `Design tokens extracted from ${t.meta.url} by Peeko (DTCG-style)`,
    color,
    fontFamily: idx(t.fontFamilies, (f) => ({ $value: [f], $type: 'fontFamily' })),
    fontSize: idx(t.fontSizes, (s) => ({ $value: s, $type: 'dimension' })),
    fontWeight: idx(t.fontWeights, (w) => ({ $value: w, $type: 'fontWeight' })),
    lineHeight: idx(t.lineHeights, (l) => ({ $value: l, $type: 'number' })),
    spacing: idx(t.spacing, (s) => ({ $value: s, $type: 'dimension' })),
    radius: idx(t.radii, (r) => ({ $value: r, $type: 'dimension' })),
    shadow: idx(t.shadows, (s) => ({ $value: s, $type: 'shadow' })),
    gradient: idx(t.gradients, (g) => ({ $value: g, $type: 'gradient' })),
    breakpoint: idx(t.breakpoints, (b) => ({ $value: b, $type: 'dimension' })),
  };
  return JSON.stringify(doc, null, 2) + '\n';
}

export function exportMarkdown(t: DesignTokens): string {
  const L: string[] = [];
  L.push(`# Design System — ${t.meta.title || t.meta.url}`, '');
  L.push(`Source: ${t.meta.url}`, '', `Generated by Peeko · ${t.meta.elementCount} elements`, '');
  if (Object.keys(t.roles).length) {
    L.push('## Color roles', '', '| Role | Value |', '| --- | --- |');
    for (const [k, v] of Object.entries(t.roles)) L.push(`| ${k} | \`${v}\` |`);
    L.push('');
  }
  L.push('## Colors', '', t.colors.map((c) => `\`${c}\``).join(' ') || '_none_', '');
  L.push('## Typography', '');
  L.push(`- Families: ${list(t.fontFamilies)}`);
  L.push(`- Sizes: ${list(t.fontSizes)}`);
  L.push(`- Weights: ${list(t.fontWeights.map(String))}`);
  L.push(`- Line heights: ${list(t.lineHeights)}`, '');
  L.push('## Spacing', '', list(t.spacing), '');
  if (t.radii.length) L.push('## Radii', '', list(t.radii), '');
  if (t.shadows.length) L.push('## Shadows', '', ...t.shadows.map((s) => `- \`${s}\``), '');
  if (t.gradients.length) L.push('## Gradients', '', ...t.gradients.map((g) => `- \`${g}\``), '');
  if (t.breakpoints.length) L.push('## Breakpoints', '', list(t.breakpoints), '');
  return L.join('\n');
}

const ROLE_USE: Record<string, string> = {
  background: 'page / surface background',
  text: 'body text',
  link: 'links',
  heading: 'headings',
  accent: 'primary buttons / emphasis',
  border: 'borders / dividers',
};

export function exportAgentBrief(t: DesignTokens): string {
  const L: string[] = [];
  L.push(`# Design System Analysis — ${t.meta.title || t.meta.url}`, '');
  L.push(`> Source: ${t.meta.url}`, `> Extracted by Peeko · ${t.meta.elementCount} elements · ${t.meta.generatedAt}`, '');
  L.push('## Summary', '');
  L.push(
    `This page uses ${t.colors.length} notable colors, ${t.fontFamilies.length} font ${plural(t.fontFamilies.length, 'family', 'families')}, a type scale of ${t.fontSizes.length} sizes, and ${t.spacing.length} spacing steps. Use the tokens below to reproduce its look — prefer the semantic roles for intent and the numbered scales for raw values.`,
    '',
  );
  if (Object.keys(t.roles).length) {
    L.push('## Semantic color roles', '', '| Role | Value | Use for |', '| --- | --- | --- |');
    for (const [k, v] of Object.entries(t.roles)) L.push(`| ${k} | \`${v}\` | ${ROLE_USE[k] ?? '—'} |`);
    L.push('');
  }
  L.push('## Palette', '', t.colors.map((c) => `\`${c}\``).join(' ') || '_none_', '');
  L.push('## Typography', '');
  L.push(`- **Families:** ${list(t.fontFamilies)} (apply the first as the base \`font-family\`).`);
  L.push(`- **Type scale:** ${list(t.fontSizes)}`);
  L.push(`- **Weights:** ${list(t.fontWeights.map(String))}`);
  L.push(`- **Line heights:** ${list(t.lineHeights)}`, '');
  L.push('## Spacing scale', '', t.spacing.length ? `${list(t.spacing)}${baseUnit(t.spacing)}` : '_none_', '');
  if (t.radii.length) L.push('## Radii', '', list(t.radii), '');
  if (t.shadows.length) L.push('## Shadows', '', ...t.shadows.map((s) => `- \`${s}\``), '');
  if (t.gradients.length) L.push('## Gradients', '', ...t.gradients.map((g) => `- \`${g}\``), '');
  if (t.breakpoints.length) L.push('## Breakpoints', '', list(t.breakpoints), '');
  L.push('## Replication notes', '');
  L.push(
    '- Define the tokens as CSS variables (block below) and reference them instead of hard-coding values.',
    '- Map the semantic roles to components: `background`/`text` for the page base, `accent` for primary actions, `link` for anchors.',
    '- Treat the smallest recurring spacing value as the base unit and build larger gaps from multiples of it.',
    '- Use the top of the type scale for headings and the most common size for body text.',
    '',
  );
  L.push('## Tokens (CSS)', '', '```css', exportCss(t).trimEnd(), '```', '');
  return L.join('\n');
}

function list(a: string[]): string {
  return a.length ? a.map((x) => `\`${x}\``).join(', ') : '_none_';
}

function plural(n: number, one: string, many: string): string {
  return n === 1 ? one : many;
}

function baseUnit(spacing: string[]): string {
  const first = spacing[0];
  return first ? ` — base unit ≈ \`${first}\`.` : '';
}
