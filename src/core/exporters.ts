import type { DesignTokens, TypeStyle } from './messaging';
import { quoteFamily } from './extract';
import { contrastRatio, wcagLevel } from './color';

// Pure exporters: DesignTokens in, string out. Unit-tested in exporters.test.ts.

type Pair = [string, string];

/** Base variable names (no sigil) shared by the CSS and SCSS exporters. */
function baseGroups(t: DesignTokens): { title: string; pairs: Pair[] }[] {
  return [
    { title: 'Colors', pairs: t.colors.map((c, i): Pair => [`color-${i + 1}`, c]) },
    { title: 'Color roles', pairs: Object.entries(t.roles).map(([k, v]): Pair => [`color-${k}`, v]) },
    {
      title: 'Font families',
      pairs: t.fontFamilies.map((f, i): Pair => [`font-${i + 1}`, `${quoteFamily(f)}, sans-serif`]),
    },
    { title: 'Font sizes', pairs: t.fontSizes.map((s, i): Pair => [`text-${i + 1}`, s]) },
    { title: 'Font weights', pairs: t.fontWeights.map((w, i): Pair => [`weight-${i + 1}`, String(w)]) },
    { title: 'Line heights', pairs: t.lineHeights.map((l, i): Pair => [`leading-${i + 1}`, l]) },
    { title: 'Spacing', pairs: t.spacing.map((s, i): Pair => [`space-${i + 1}`, s]) },
    { title: 'Radii', pairs: t.radii.map((r, i): Pair => [`radius-${i + 1}`, r]) },
    { title: 'Shadows', pairs: t.shadows.map((s, i): Pair => [`shadow-${i + 1}`, s]) },
    { title: 'Gradients', pairs: t.gradients.map((g, i): Pair => [`gradient-${i + 1}`, g]) },
    { title: 'Breakpoints', pairs: t.breakpoints.map((b, i): Pair => [`bp-${i + 1}`, b]) },
  ].filter((g) => g.pairs.length > 0);
}

export function exportCss(t: DesignTokens): string {
  const out = [':root {'];
  for (const g of baseGroups(t)) {
    out.push(`  /* ${g.title} */`);
    for (const [k, v] of g.pairs) out.push(`  --${k}: ${v};`);
  }
  out.push('}');
  return out.join('\n') + '\n';
}

export function exportScss(t: DesignTokens): string {
  const out: string[] = [];
  for (const g of baseGroups(t)) {
    out.push(`// ${g.title}`);
    for (const [k, v] of g.pairs) out.push(`$${k}: ${v};`);
    out.push('');
  }
  return out.join('\n');
}

export function exportTailwind(t: DesignTokens): string {
  const out = ['@import "tailwindcss";', '', '@theme {'];
  const sec = (title: string, pairs: Pair[]) => {
    if (pairs.length === 0) return;
    out.push(`  /* ${title} */`);
    for (const [k, v] of pairs) out.push(`  --${k}: ${v};`);
  };
  sec('Colors', t.colors.map((c, i): Pair => [`color-${i + 1}`, c]));
  sec('Color roles', Object.entries(t.roles).map(([k, v]): Pair => [`color-${k}`, v]));
  sec('Fonts', t.fontFamilies.map((f, i): Pair => [i === 0 ? 'font-sans' : `font-${i + 1}`, `${quoteFamily(f)}, sans-serif`]));
  sec('Text sizes', t.fontSizes.map((s, i): Pair => [`text-${i + 1}`, s]));
  sec('Spacing', t.spacing.map((s, i): Pair => [`spacing-${i + 1}`, s]));
  sec('Radius', t.radii.map((r, i): Pair => [`radius-${i + 1}`, r]));
  sec('Shadow', t.shadows.map((s, i): Pair => [`shadow-${i + 1}`, s]));
  out.push('}');
  return out.join('\n') + '\n';
}

export function exportJson(t: DesignTokens): string {
  const idx = <T>(arr: T[], make: (v: T) => unknown): Record<string, unknown> => {
    const o: Record<string, unknown> = {};
    arr.forEach((v, i) => {
      o[String(i + 1)] = make(v);
    });
    return o;
  };
  const color: Record<string, unknown> = idx(t.colors, (c) => ({ $value: c, $type: 'color' }));
  for (const [k, v] of Object.entries(t.roles)) color[k] = { $value: v, $type: 'color' };

  const doc = {
    $description: `Design tokens extracted from ${t.meta.url} by Peeko (DTCG-style)`,
    color,
    fontFamily: idx(t.fontFamilies, (f) => ({ $value: [f], $type: 'fontFamily' })),
    fontSize: idx(t.fontSizes, (s) => ({ $value: s, $type: 'dimension' })),
    fontWeight: idx(t.fontWeights, (w) => ({ $value: w, $type: 'fontWeight' })),
    lineHeight: idx(t.lineHeights, (l) => ({ $value: l, $type: 'number' })),
    spacing: idx(t.spacing, (s) => ({ $value: s, $type: 'dimension' })),
    radius: idx(t.radii, (r) => ({ $value: r, $type: 'dimension' })),
    shadow: idx(t.shadows, (s) => ({ $value: s, $type: 'shadow' })),
    gradient: idx(t.gradients, (g) => ({ $value: g, $type: 'gradient' })),
    breakpoint: idx(t.breakpoints, (b) => ({ $value: b, $type: 'dimension' })),
    // Semantic/component data doesn't map to DTCG token types — kept under $extensions.
    $extensions: {
      'com.peeko': {
        headings: t.headings,
        body: t.body,
        bodyColor: t.bodyColor,
        components: t.components,
        baseUnit: t.baseUnit,
      },
    },
  };
  return JSON.stringify(doc, null, 2) + '\n';
}

export function exportMarkdown(t: DesignTokens): string {
  const L: string[] = [];
  L.push(`# Design System — ${t.meta.title || t.meta.url}`, '');
  L.push(`Source: ${t.meta.url}`, '', `Generated by Peeko · ${t.meta.elementCount} elements`, '');

  if (Object.keys(t.roles).length) {
    L.push('## Color roles', '', '| Role | Value | Use for |', '| --- | --- | --- |');
    for (const [k, v] of Object.entries(t.roles)) L.push(`| ${k} | \`${v}\` | ${ROLE_USE[k] ?? '—'} |`);
    L.push('');
  }
  L.push('## Colors', '', t.colors.map((c) => `\`${c}\``).join(' ') || '_none_', '');

  L.push('## Typography', '');
  L.push(`- Families: ${list(t.fontFamilies)}`);
  L.push(`- Type scale: ${list(t.fontSizes)}`);
  L.push(`- Weights: ${list(t.fontWeights.map(String))}`);
  L.push(`- Line heights: ${list(t.lineHeights)}`, '');
  L.push(...headingSection(t));
  L.push(...bodyLinkLines(t), '');

  L.push('## Spacing', '', t.spacing.length ? `${list(t.spacing)}${baseNote(t)}` : '_none_', '');
  if (t.breakpoints.length) L.push('## Breakpoints', '', list(t.breakpoints), '');
  L.push(...componentSections(t));
  if (t.radii.length) L.push('## Radii', '', list(t.radii), '');
  if (t.shadows.length) L.push('## Shadows', '', ...t.shadows.map((s) => `- \`${s}\``), '');
  if (t.gradients.length) L.push('## Gradients', '', ...t.gradients.map((g) => `- \`${g}\``), '');
  return L.join('\n');
}

const ROLE_USE: Record<string, string> = {
  background: 'page / surface background',
  text: 'body text',
  link: 'links',
  heading: 'headings',
  accent: 'primary buttons / emphasis',
  border: 'borders / dividers',
};

const COMPONENT_TITLE: Record<string, string> = {
  button: 'Button',
  link: 'Link',
  input: 'Input / field',
};

export function exportAgentBrief(t: DesignTokens): string {
  const L: string[] = [];
  L.push(`# Design System — ${t.meta.title || t.meta.url}`, '');
  L.push(
    `> A design reference for AI agents. Reproduce this product's look by using **only** the tokens, type scale and component specs below.`,
    `> Source: ${t.meta.url} · Extracted by Peeko · ${t.meta.elementCount} elements · ${t.meta.generatedAt}`,
    '',
  );

  L.push('## Overview', '');
  L.push(
    `${t.colors.length} notable colors, ${t.fontFamilies.length} font ${plural(t.fontFamilies.length, 'family', 'families')}, a ${t.fontSizes.length}-step type scale, ${t.spacing.length} spacing steps${t.breakpoints.length ? `, ${t.breakpoints.length} breakpoints` : ''}. Prefer the **semantic roles** for intent and the **numbered scales** for raw values.`,
    '',
  );

  L.push('## Design principles', '', ...principles(t), '');

  L.push('## Color system', '');
  if (Object.keys(t.roles).length) {
    L.push('### Roles', '', '| Role | Value | Use for |', '| --- | --- | --- |');
    for (const [k, v] of Object.entries(t.roles)) L.push(`| ${k} | \`${v}\` | ${ROLE_USE[k] ?? '—'} |`);
    const c = contrastNote(t);
    L.push('', ...(c ? [`Contrast — ${c}`, ''] : []));
  }
  L.push('### Palette', '', t.colors.map((c) => `\`${c}\``).join(' ') || '_none_', '');

  L.push('## Typography', '');
  L.push(`- **Families:** ${list(t.fontFamilies)} — apply the first as the base \`font-family\`.`);
  L.push(`- **Type scale:** ${list(t.fontSizes)}`);
  L.push(`- **Weights:** ${list(t.fontWeights.map(String))}`);
  L.push(`- **Line heights:** ${list(t.lineHeights)}`, '');
  L.push(...headingSection(t));
  L.push(...bodyLinkLines(t), '');

  L.push('## Spacing & layout', '');
  L.push(`- **Spacing scale:** ${t.spacing.length ? list(t.spacing) : '_none_'}${baseNote(t)}`);
  if (t.breakpoints.length) L.push(`- **Breakpoints:** ${list(t.breakpoints)}`);
  L.push('');

  L.push(...componentSections(t));

  if (t.radii.length || t.shadows.length || t.gradients.length) {
    L.push('## Effects', '');
    if (t.radii.length) L.push(`- **Radii:** ${list(t.radii)}`);
    if (t.shadows.length) L.push('- **Shadows:**', ...t.shadows.map((s) => `  - \`${s}\``));
    if (t.gradients.length) L.push('- **Gradients:**', ...t.gradients.map((g) => `  - \`${g}\``));
    L.push('');
  }

  L.push('## Rules for agents', '');
  L.push(
    '**Do**',
    '- Use only the colors in the palette/roles above; map roles to intent (background, text, accent, link).',
    t.baseUnit ? `- Base every gap, padding and margin on multiples of \`${t.baseUnit}\`.` : '- Keep spacing on the scale above.',
    '- Use the listed font families; size headings per the Headings table, body per the body size.',
    '- Reuse the listed radii and shadows so elevation and shape stay consistent.',
    '',
    '**Don\'t**',
    '- Introduce new fonts, arbitrary hex colors, or off-scale spacing/font sizes.',
    '- Enlarge headings beyond the scale, or add shadows/radii not listed.',
    '- Invent component styles that contradict the Components section.',
    '',
  );

  L.push('## Tokens (CSS)', '', '```css', exportCss(t).trimEnd(), '```', '');
  return L.join('\n');
}

// --- shared markdown helpers ---

function list(a: string[]): string {
  return a.length ? a.map((x) => `\`${x}\``).join(', ') : '_none_';
}

function plural(n: number, one: string, many: string): string {
  return n === 1 ? one : many;
}

function baseNote(t: DesignTokens): string {
  return t.baseUnit ? ` — base unit ≈ \`${t.baseUnit}\`.` : '';
}

function headingSection(t: DesignTokens): string[] {
  const keys = Object.keys(t.headings);
  if (!keys.length) return [];
  const rows = ['### Headings', '', '| Element | Size | Weight | Line height |', '| --- | --- | --- | --- |'];
  for (const k of keys) {
    const s = t.headings[k] as TypeStyle;
    rows.push(`| ${k} | ${s.size} | ${s.weight} | ${s.lineHeight} |`);
  }
  rows.push('');
  return rows;
}

function bodyLinkLines(t: DesignTokens): string[] {
  const out: string[] = [];
  if (t.body) {
    out.push(
      `- **Body:** ${t.body.size} / weight ${t.body.weight} / line-height ${t.body.lineHeight}${t.bodyColor ? ` / color \`${t.bodyColor}\`` : ''}.`,
    );
  }
  const link = t.components.link;
  if (link) {
    const parts = Object.entries(link).map(([k, v]) => `${k} \`${v}\``);
    out.push(`- **Links:** ${parts.join(', ')}.`);
  }
  return out;
}

function componentSections(t: DesignTokens): string[] {
  const names = Object.keys(t.components).filter((n) => n !== 'link');
  if (!names.length) return [];
  const out = ['## Components', ''];
  for (const name of names) {
    const props = t.components[name];
    if (!props || Object.keys(props).length === 0) continue;
    out.push(`### ${COMPONENT_TITLE[name] ?? name}`, '', '| Property | Value |', '| --- | --- |');
    for (const [k, v] of Object.entries(props)) out.push(`| ${k} | \`${v}\` |`);
    out.push('');
  }
  return out;
}

function principles(t: DesignTokens): string[] {
  const out: string[] = [];
  if (t.baseUnit) out.push(`- **Spacing rhythm:** base unit ≈ \`${t.baseUnit}\`; scale ${list(t.spacing)}.`);
  if (t.radii.length) {
    const sharp = t.radii.every((r) => (parseFloat(r) || 0) <= 4);
    out.push(`- **Corners:** ${sharp ? 'sharp / minimal rounding' : 'rounded'} (${list(t.radii)}).`);
  } else {
    out.push('- **Corners:** square — no border-radius detected.');
  }
  const first = t.fontSizes[0];
  const last = t.fontSizes[t.fontSizes.length - 1];
  if (first && last && t.fontSizes.length >= 2) {
    out.push(`- **Type scale:** ${t.fontSizes.length} sizes, from ${first} to ${last}.`);
  }
  out.push(`- **Elevation:** ${t.shadows.length ? `${t.shadows.length} shadow level(s)` : 'flat — no shadows'}.`);
  return out;
}

function contrastNote(t: DesignTokens): string | null {
  const bg = t.roles.background;
  const text = t.roles.text ?? t.bodyColor ?? undefined;
  if (!bg || !text) return null;
  const r = contrastRatio(text, bg);
  if (r === null) return null;
  return `body text \`${text}\` on \`${bg}\` = **${r.toFixed(2)}:1** (${wcagLevel(r)}).`;
}
